CREATE DATABASE IF NOT EXISTS expense_tracker CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE expense_tracker;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 currency VARCHAR(8) NOT NULL DEFAULT 'INR', password_hint VARCHAR(120) NOT NULL DEFAULT '', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS transactions (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 type ENUM('income','expense') NOT NULL, category VARCHAR(80) NOT NULL,
 amount DECIMAL(12,2) NOT NULL, transaction_date DATE NOT NULL,
 description VARCHAR(255) NOT NULL DEFAULT '', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_user_date(user_id,transaction_date),
 CONSTRAINT fk_et_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS budgets (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 month_key CHAR(7) NOT NULL, amount DECIMAL(12,2) NOT NULL,
 UNIQUE KEY unique_user_month(user_id,month_key),
 CONSTRAINT fk_eb_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
